"""Export a small, credential-free source kit for local native desktop builds."""
import hashlib
import json
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED

ROOT = Path(__file__).resolve().parents[1]
VERSION = json.loads((ROOT / "artifacts/sonora-ai/package.json").read_text())["version"]
OUTPUT = ROOT / "generated-artifacts" / f"sonora-desktop-build-kit-{VERSION}.zip"
ROOT_FILES = (
    "BUILD-WINDOWS.cmd", "package.json", "pnpm-lock.yaml", "pnpm-workspace.yaml",
    "tsconfig.json", "tsconfig.base.json", ".gitignore", ".replitignore",
)
TREES = ("artifacts/sonora-ai", "artifacts/api-server", "lib", "scripts")
EXCLUDED = {
    "node_modules", ".git", ".local", ".agents", "dist", "target",
    "generated-artifacts", "__pycache__", "attached_assets",
}
ALLOWED_SUFFIXES = {
    ".ts", ".tsx", ".js", ".cjs", ".mjs", ".json", ".yaml", ".yml",
    ".md", ".rs", ".toml", ".lock", ".txt", ".plist", ".cmd", ".sh",
    ".css", ".html", ".svg", ".png", ".jpg", ".jpeg", ".webp", ".ico",
}
INSTRUCTIONS = """# Sonora desktop build kit

This ZIP contains SOURCE for local builds, not an installer. It contains no
credentials or user-uploaded files. Windows builds do not need a GitHub account.

1. The publisher must first republish the latest Sonora service. The builder
   deliberately stops if that service lacks the new browser sign-in protocol.
2. Extract this ZIP to a normal folder. On Windows x64, read
   artifacts/sonora-ai/desktop/WINDOWS.md for Node, pnpm, Rust, and compiler/SDK
   prerequisites. Double-click BUILD-WINDOWS.cmd and supply the published URL.
3. The resulting installer is in generated-artifacts/installers. It is an
   unsigned preview unless a signing identity is configured on your build PC.
4. Install it, choose Sign in with browser, sign in using Google or email,
   and enter the desktop's six-digit code in the browser. Return to Sonora.
5. Follow desktop/VERIFICATION.md on the target computer: real sign-in,
   microphone AND interviewer/system audio, Gemini answers, Stop/Quit,
   Hide/tray restore, and receiver-side screen sharing. A toggle alone does not
   prove screen-share exclusion. macOS ScreenCaptureKit may ignore protection.

Mac builds must run on a Mac; see desktop/README.md. Signing/notarization and
native receiver-side verification are still required before a verified release.
Do not distribute a build as verified merely because the build command passed.
"""


def export():
    files = {ROOT / name for name in ROOT_FILES if (ROOT / name).is_file()}
    for tree in TREES:
        for file in (ROOT / tree).rglob("*"):
            rel = file.relative_to(ROOT)
            if not file.is_file() or file.is_symlink() or any(p in EXCLUDED for p in rel.parts):
                continue
            if file.name.startswith(".") or (file.suffix not in ALLOWED_SUFFIXES
                and file.name not in {"LICENSE", "LICENSE-MIT", "LICENSE-APACHE", "NOTICE"}):
                continue
            if rel.parts[:4] == ("artifacts", "sonora-ai", "desktop", "assets"):
                continue  # regenerated by the build, never needed in the kit
            if file.name in {"runtime-config.json"} and file.parent.name != "desktop":
                continue
            files.add(file)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    prefix = f"Sonora-{VERSION}"
    with ZipFile(OUTPUT, "w", compression=ZIP_DEFLATED) as archive:
        for file in sorted(files):
            archive.write(file, f"{prefix}/{file.relative_to(ROOT).as_posix()}")
        archive.writestr(f"{prefix}/START-HERE.md", INSTRUCTIONS)
    checksum = hashlib.sha256(OUTPUT.read_bytes()).hexdigest()
    OUTPUT.with_suffix(".zip.sha256").write_text(f"{checksum}  {OUTPUT.name}\n")
    print(f"{OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size:,} bytes; {len(files)} source files)")
    print(f"SHA256 {checksum}")


if __name__ == "__main__":
    export()
